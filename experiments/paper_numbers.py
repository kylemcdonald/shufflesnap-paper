"""Every derived number quoted in the paper's prose, recomputed from the raw results.

    SS_RESULTS_RAW=results/raw_geometric python experiments/paper_numbers.py

Tables and figures are generated by make_tables.py / make_figures.py; this script prints
the statistics the text cites (medians, ranges, ratios, crossover times, fitted exponents),
grouped by paper section, so that the text can be checked against the data.
"""
from __future__ import annotations

import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import analysis  # noqa: E402

SS = ["SS-fast", "SS-balanced", "SS-quality"]
DEF = "SS-balanced"  # the default preset


def ok(d):
    return d[d["error"].isna() & (d["valid"] == True)] if "error" in d else d  # noqa: E712


def med(s):
    return float(np.median(s)) if len(s) else float("nan")


def rng(xs, fmt="{:.3g}"):
    xs = [x for x in xs if x == x]
    return (fmt + "–" + fmt).format(min(xs), max(xs)) if xs else "n/a"


def section(t):
    print(f"\n=== {t}")


def main():
    df = analysis.load()
    df = df.copy()
    exact_ss = (df["label"] == "Exact-certified")

    section("main, N=1e5, 1 thread (Table main, Section main)")
    m1 = df[df["file"].str.startswith("main") & (df["threads"] == 1) & (df["n"] == 100000) & (df["grid"] == "square")]
    for lab in SS + ["BSP-OT-16", "BSP-OT-64", "RasterFairy-master", "RasterFairy-pypi"]:
        s = ok(m1[m1["label"] == lab])
        print(f"  {lab:20s} median time {med(s['time_s']):.3g} s over {len(s)} runs")
    ex = ok(m1[exact_ss.loc[m1.index]])
    base = ok(m1[(m1["label"] == DEF) & (m1["seed"] == 1)]).set_index("dist")["time_s"]
    exs = ex.set_index("dist")["time_s"]
    print(f"  exact from SS: {len(exs)} instances, time {rng(exs)} s, median {med(exs):.3g} s;"
          f" min at {exs.idxmin()}, max at {exs.idxmax()}")
    ratio = (exs / base.reindex(exs.index)).dropna()
    print(f"  exact / default preset time (seed 1): {rng(ratio)}x, median {med(ratio):.3g}x")
    bis = m1[m1["label"] == "Exact-certified-bisect"].set_index("dist")
    rows = []
    for dist, r in bis.iterrows():
        e = "cert" if r.get("exact_status") == "certified" else f"{r.get('exact_status')}: {str(r.get('error'))[:30]}"
        rows.append((dist, r.get("time_s"), exs.get(dist), e))
    for dist, tb, ts, e in rows:
        print(f"    bisect {dist:18s} {tb if tb == tb else float('nan'):9.4g} s  vs SS-start {ts:9.4g} s   {e}"
              + (f"  ratio {tb / ts:.3g}" if tb == tb and e == "cert" else ""))

    section("main, N=1e5, 24 threads (Section main, 'With all cores')")
    m24 = df[df["file"].str.startswith("main") & (df["threads"] == 24) & (df["n"] == 100000) & (df["grid"] == "square")]
    for lab in SS + ["BSP-OT-16", "BSP-OT-64"]:
        s = ok(m24[m24["label"] == lab])
        print(f"  {lab:20s} median time {med(s['time_s']):.3g} s")
    key = ["label", "dist", "seed"]
    j = ok(m1).merge(ok(m24), on=key, suffixes=("_1", "_24"))
    for fam, labs in (("ShuffleSnap", SS), ("BSP-OT", ["BSP-OT-16", "BSP-OT-64"])):
        jj = j[j["label"].isin(labs)]
        sp = jj["time_s_1"] / jj["time_s_24"]
        print(f"  {fam} speed-up 1->24 threads: {rng(sp)}x (median {med(sp):.3g}x) over {len(jj)} pairs")
    jj = j[j["label"].isin(SS)]
    print(f"  ShuffleSnap identical cost 1 vs 24 threads: {(jj['cost_1'] == jj['cost_24']).sum()} of {len(jj)}")
    b24 = ok(m24[m24["label"] == DEF]).groupby("dist")["excess_pct"].mean()
    p24 = ok(m1[m1["label"] == "BSP-OT-64"]).groupby("dist")["excess_pct"].mean()
    print(f"  default better than BSP-OT-64 on {(b24 < p24.reindex(b24.index)).sum()} of {len(b24)} distributions;"
          f" exceptions: {list(b24.index[~(b24 < p24.reindex(b24.index))])}")
    bal24 = ok(m24[m24["label"] == "SS-balanced"]).groupby("dist")["time_s"].median()
    print(f"  balanced, 24 threads, per-distribution median time: {rng(bal24)} s")

    section("main, N=1e4 and 5e4 (appendix tables)")
    for n in (10000, 50000):
        mm = df[df["file"].str.startswith("main") & (df["threads"] == 1) & (df["n"] == n) & (df["grid"] == "square")]
        e = ok(mm[mm["label"] == "Exact-certified"])["time_s"]
        print(f"  N={n}: exact from SS {rng(e)} s; " + ", ".join(
            f"{lab} {med(ok(mm[mm['label'] == lab])['time_s']):.3g}s" for lab in SS))
        d = ok(mm[mm["label"] == "Exact-dense-scipy"])["time_s"]
        if len(d):
            print(f"    dense scipy {rng(d)} s")

    section("anytime (Section anytime)")
    an = df[df["file"].str.startswith("anytime")]
    for T in sorted(an["threads"].unique()):
        a = an[an["threads"] == T]
        for dist in ["uniform", "gmm", "mnist"]:
            s = a[a["dist"] == dist]
            bsp = ok(s[s["label"].str.startswith("BSP-OT")]).copy()
            bsp["k"] = bsp["label"].str.split("-").str[-1].astype(int)
            bsp = bsp.sort_values("time_s")
            best = bsp["excess_pct"].min()
            r = s[s["label"] == DEF].iloc[0]
            tr = np.array(r["trace"])
            opt = r["ref_cost"]
            t, e = tr[:, 0], 100 * (tr[:, 1] / opt - 1)
            passed = t[np.argmax(e <= best)] if (e <= best).any() else float("nan")

            def bsp_at(x):  # best BSP-OT result available within a budget x
                v = bsp.loc[bsp["time_s"] <= x, "excess_pct"]
                return v.min() if len(v) else np.inf

            # earliest time from which ShuffleSnap's trace is ahead of BSP-OT at every later time
            cand = sorted(set(t) | set(bsp["time_s"]))
            ahead_from = float("nan")
            for x in reversed(cand):
                ss_e = e[t <= x].min() if (t <= x).any() else np.inf
                if ss_e < bsp_at(x):
                    ahead_from = x
                else:
                    break
            k = {kk: v for kk, v in zip(bsp["k"], bsp["excess_pct"])}
            tk = {kk: v for kk, v in zip(bsp["k"], bsp["time_s"])}
            print(f"  t{T} {dist:8s} BSP 1/16/1024 plans {k.get(1, np.nan):.3g}/{k.get(16, np.nan):.3g}/{k.get(1024, np.nan):.3g}%"
                  f" (1024 plans {tk.get(1024, np.nan):.3g}s); SS default passes best BSP at {passed:.3g}s,"
                  f" ahead from {ahead_from:.3g}s, finishes {e[-1]:.3g}% at {t[-1]:.3g}s")

    section("scaling (Section scaling)")
    sc = df[df["file"].str.startswith("scaling")]
    for T in (1, 24):
        s = ok(sc[sc["threads"] == T])
        for dist in ("uniform", "gmm"):
            for lab in SS + ["BSP-OT-16", "RasterFairy-master", "Exact-certified"]:
                x = s[(s["dist"] == dist) & (s["label"] == lab) & (s["grid"] == "square")].sort_values("n")
                x = x[x["n"] >= 10000]
                if len(x) < 2:
                    continue
                expo = np.polyfit(np.log(x["n"]), np.log(x["time_s"]), 1)[0]
                top = x.iloc[-1]
                extra = ""
                if lab == "Exact-certified":
                    extra = f", peak {top['peak_rss_mb'] / 1024:.2f} GB"
                print(f"  t{T} {dist:8s} {lab:20s} exponent {expo:.2f}; N={int(top['n'])}: {top['time_s']:.3g} s"
                      f" ({top['time_s'] / 60:.3g} min){extra}")

    section("threads (Section threads)")
    th = ok(df[df["file"].str.startswith("threads")])
    for dist in ("uniform", "gmm"):
        for lab in ("SS-fast", "SS-balanced", "BSP-OT-16"):
            s = th[(th["dist"] == dist) & (th["label"] == lab)].groupby("threads")["time_s"].median()
            if s.empty:
                continue
            print(f"  {dist:8s} {lab:12s} 1 thread {s.iloc[0]:.3g}s; speed-up "
                  + ", ".join(f"{int(k)}:{s.iloc[0] / v:.1f}x" for k, v in s.items()))

    section("ablations (Section ablation, 24 threads)")
    ab = ok(df[df["file"].str.startswith("ablations")]).copy()
    ab["group"] = ab["label"].str.replace("abl-", "", regex=False)
    for dist in ("uniform", "gmm", "mnist"):
        a = ab[ab["dist"] == dist]
        w = a[a["group"] == "window"].groupby("p_window").agg(e=("excess_pct", "mean"), t=("time_s", "median"))
        expo = np.polyfit(np.log(w.index.astype(float)), np.log(w["t"]), 1)[0]
        print(f"  {dist:8s} window (ratio 2): " + ", ".join(f"w{int(k)} {r.e:.3g}%/{r.t:.3g}s" for k, r in w.iterrows())
              + f"; time ~ w^{expo:.2f}")
        wr = a[a["group"] == "window-r1.41"].groupby("p_window").agg(e=("excess_pct", "mean"), t=("time_s", "median"))
        print(f"  {dist:8s} window (ratio sqrt2): " + ", ".join(f"w{int(k)} {r.e:.3g}%/{r.t:.3g}s" for k, r in wr.iterrows()))
        c = a[a["group"] == "coarse"].copy()
        c["cap"] = c["p_start_stride"].map(lambda v: "auto" if v != v or v is None else int(v))
        cg = c.groupby("cap", sort=False).agg(e=("excess_pct", "mean"), t=("time_s", "median"))
        auto = cg.loc["auto"]
        capped = cg.drop("auto")
        print(f"  {dist:8s} coarse: " + ", ".join(f"{k}: {r.e:.3g}%/{r.t:.3g}s" for k, r in cg.iterrows())
              + f"; capped worse {rng(capped.e / auto.e)}x, slower {rng(capped.t / auto.t)}x")
        o = a[a["group"] == "offsets"].copy()
        o["k"] = o["p_offsets"].map(lambda v: len(json.loads(v)) if isinstance(v, str) else 4)
        og = o.groupby("k").agg(e=("excess_pct", "mean"), t=("time_s", "median"))
        print(f"  {dist:8s} tilings: " + ", ".join(f"{k}: {r.e:.3g}%/{r.t:.3g}s ({r.t / og.loc[4].t:.2f}x)" for k, r in og.iterrows()))
        rr = a[a["group"] == "rounds"].groupby("p_rounds").agg(e=("excess_pct", "mean"), t=("time_s", "median"))
        print(f"  {dist:8s} rounds: " + ", ".join(f"{int(k)}: {r.e:.3g}%/{r.t:.3g}s ({r.t / rr.iloc[0].t:.2f}x)" for k, r in rr.iterrows()))
        ra = a[a["group"] == "ratio"].groupby("p_ratio").agg(e=("excess_pct", "mean"), t=("time_s", "median"))
        print(f"  {dist:8s} ratio: " + ", ".join(f"{float(k):.3g}: {r.e:.3g}%/{r.t:.3g}s" for k, r in ra.iterrows()))
        st = a[a["group"] == "start"].groupby("p_init").agg(e=("excess_pct", "mean"), t=("time_s", "median"))
        print(f"  {dist:8s} start: " + ", ".join(f"{k}: {r.e:.3g}%/{r.t:.3g}s" for k, r in st.iterrows()))
        sk = a[a["group"] == "skip_clean"].groupby("p_skip_clean").agg(e=("excess_pct", "mean"), t=("time_s", "median"))
        print(f"  {dist:8s} skip unchanged: saves {100 * (1 - sk.loc[True].t / sk.loc[False].t):.0f}% "
              f"(excess {sk.loc[True].e:.4g} vs {sk.loc[False].e:.4g})")
        sv = a[a["group"] == "solver"].groupby(["p_window", "p_ratio", "p_solver"]).agg(e=("excess_pct", "mean"), t=("time_s", "median"))
        for (wv, rv), g in sv.groupby(level=[0, 1]):
            ref = g.xs("hungarian_greedy", level=2).t.iloc[0]
            print(f"  {dist:8s} solver w{int(wv)} r{float(rv):.3g}: " + ", ".join(
                f"{k[2]} {r.t:.3g}s ({r.t / ref:.2f}x greedy)" for k, r in g.iterrows())
                + f"; excess identical: {g.e.nunique() == 1 or (g.e.max() - g.e.min()) < 1e-6}")

    section("solver comparison at the balanced preset (solver_balanced, 1 and 24 threads)")
    sb = ok(df[df["file"].str.startswith("solver_balanced")])
    for T in (24, 1):
        for dist in ("mnist", "gmm", "uniform"):
            s = sb[(sb["threads"] == T) & (sb["dist"] == dist)].groupby("p_solver").agg(t=("time_s", "median"), e=("excess_pct", "mean"))
            if s.empty:
                continue
            ref = s.loc["hungarian_greedy"].t
            print(f"  t{T} {dist:8s} " + ", ".join(f"{k} {r.t:.3g}s ({ref / r.t:.2f}x faster than greedy)" for k, r in s.iterrows()))

    section("memory (Table memory)")
    me = ok(df[df["file"].str.startswith("memory")])
    for lab, s in me.groupby("label"):
        bpp = (s["peak_rss_mb"] * 2 ** 20 / s["n"])
        print(f"  {lab:24s} bytes/point {rng(bpp)}; at N=1e6: "
              + ", ".join(f"{d} {r.peak_rss_mb:.3g} MB" for d, r in s[s["n"] == 1000000].set_index("dist").iterrows()))

    section("correctness")
    mm = df[df["file"].str.startswith("main")]
    done = mm[mm["error"].isna()]
    print(f"  main benchmark: {len(done)} completed runs, {int((done['valid'] == True).sum())} valid;"  # noqa: E712
          f" ShuffleSnap runs: {int((done['method'] == 'shufflesnap').sum())}")


if __name__ == "__main__":
    main()
